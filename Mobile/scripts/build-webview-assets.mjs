// Downloads pinned copies of the WebView markdown libraries once and writes
// them as string modules under src/assets/webview/, so MobileMarkdown can
// inline them instead of loading unpinned scripts from a CDN at runtime.
// Usage: node scripts/build-webview-assets.mjs
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'assets', 'webview');

const ASSETS = [
  { name: 'markedJs', file: 'marked.ts', url: 'https://cdn.jsdelivr.net/npm/marked@12.0.2/marked.min.js' },
  { name: 'markedKatexJs', file: 'markedKatex.ts', url: 'https://cdn.jsdelivr.net/npm/marked-katex-extension@5.0.1/lib/index.umd.js' },
  { name: 'hljsJs', file: 'hljs.ts', url: 'https://cdnjs.cloudflare.com/ajax/libs/highlight.js/11.9.0/highlight.min.js' },
  { name: 'hljsCss', file: 'hljsCss.ts', url: 'https://cdnjs.cloudflare.com/ajax/libs/highlight.js/11.9.0/styles/github-dark.min.css' },
];

await mkdir(OUT_DIR, { recursive: true });
for (const { name, file, url } of ASSETS) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  // Escape closing tags so the code can sit inside an inline <script>/<style>
  const text = (await res.text()).replace(/<\/(script|style)/gi, '<\\/$1');
  const body = `// Generated by scripts/build-webview-assets.mjs from ${url}. Do not edit.\n` +
    `export const ${name} = ${JSON.stringify(text)};\n`;
  await writeFile(join(OUT_DIR, file), body);
  console.log(`${file}: ${text.length} chars`);
}
